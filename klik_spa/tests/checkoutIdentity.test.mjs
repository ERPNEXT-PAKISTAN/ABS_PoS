import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
const dir = await mkdtemp(path.join(tmpdir(), 'abs-checkout-'));
try {
  const output = path.join(dir, 'checkout.mjs');
  await build({ entryPoints: [new URL('../src/services/checkoutIdentity.ts', import.meta.url).pathname], outfile: output, format: 'esm', bundle: true });
  globalThis.document = { cookie: 'user_id=cashier-a' };
  globalThis.window = { dispatchEvent() {} };
  globalThis.crypto ??= webcrypto;
  const data = new Map();
  globalThis.localStorage = { getItem: k => data.get(k) ?? null, setItem: (k, v) => data.set(k, v), removeItem: k => data.delete(k) };
  const { prepareCheckout, finishCheckout, rejectCheckout, checkoutRecord } = await import(pathToFileURL(output));
  const cart = { checkoutCartId: 'cart-1', amountPaid: 10 };
  const first = prepareCheckout(cart);
  assert.equal(prepareCheckout(cart).checkoutRequestId, first.checkoutRequestId);
  assert.throws(() => prepareCheckout({ ...cart, amountPaid: 20 }));
  finishCheckout('TEST-INVOICE');
  assert.equal(checkoutRecord().invoice, 'TEST-INVOICE');
  assert.equal(prepareCheckout(cart).checkoutRequestId, first.checkoutRequestId);
  assert.throws(() => prepareCheckout({ ...cart, amountPaid: 20 }));
  const second = prepareCheckout({ ...cart, checkoutCartId: 'cart-2' });
  assert.notEqual(second.checkoutRequestId, first.checkoutRequestId);
  document.cookie = 'user_id=cashier-b';
  assert.equal(checkoutRecord(), null);
  assert.ok(prepareCheckout(cart).checkoutRequestId);
  assert.equal(checkoutRecord().completed, undefined);
  rejectCheckout(); assert.equal(checkoutRecord(), null);
  document.cookie = 'user_id=Guest'; assert.throws(() => prepareCheckout(cart));
  const identityFile = path.join(dir, 'cart-id.mjs');
  await build({ entryPoints: [new URL('../src/utils/cartIdentity.ts', import.meta.url).pathname], outfile: identityFile, format: 'esm', bundle: true });
  const { newCartId } = await import(pathToFileURL(identityFile));
  const originalCrypto = globalThis.crypto;
  Object.defineProperty(globalThis, 'crypto', { value: { getRandomValues: webcrypto.getRandomValues.bind(webcrypto) }, configurable: true });
  assert.match(newCartId(), /^[a-f0-9]{32}$/);
  Object.defineProperty(globalThis, 'crypto', { value: originalCrypto, configurable: true });
  console.log('PASS: stable retries, ambiguous cart lock, completed replay, new cart, cashier isolation and Guest rejection');
} finally { await rm(dir, { recursive: true, force: true }); }
